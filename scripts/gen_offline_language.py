"""Write app/lib/offline/language_words.dart from content/language_words/ (backend letters.py),
so offline reading on the phone finds a Hausa, Yorùbá or Igbo page the way the server does, and
app/lib/offline/word_lists.dart from content/word_lists/, so it marks the same words that may
have lost a special letter (letters.may_miss_letter).
backend/tests/test_digit_letters.py fails if either file is out of date.

    backend/.venv/bin/python scripts/gen_offline_language.py
"""
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from app import letters  # noqa: E402

OUT = ROOT / "app" / "lib" / "offline" / "language_words.dart"
WORD_LISTS = ROOT / "app" / "lib" / "offline" / "word_lists.dart"


def plain_map() -> dict[str, str]:
    """Each accented, dotted or hooked Latin letter → its plain form (letters.plain, one letter)."""
    out = {}
    for cp in list(range(0xC0, 0x2B0)) + list(range(0x1E00, 0x1F00)):
        ch = chr(cp)
        p = letters.plain(ch)
        if ch.isalpha() and p != ch.lower() and len(p) == 1:
            out[ch] = p
    return out


def untoned_map() -> dict[str, str]:
    """Each Latin letter with a tone mark → the letter without it, dots and hooks kept
    (letters.untoned, one letter)."""
    out = {}
    for cp in list(range(0xC0, 0x2B0)) + list(range(0x1E00, 0x1F00)):
        ch = chr(cp)
        u = letters.untoned(ch)
        if ch.isalpha() and u != ch.lower() and len(u) == 1:
            out[ch] = u
    return out


def word_lists_dart() -> str:
    """Per language, one line per plain form: the plain form, then the list's words with that
    form (letters._index), space-separated. Parsed once, when first needed."""
    q = lambda s: "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"  # noqa: E731
    lines = ["// GENERATED by scripts/gen_offline_language.py from content/word_lists/: do not edit.",
             "// Words with a special letter, by plain form (backend letters._index): the offline reader marks",
             "// a word that may have lost one, as the server does (letters.may_miss_letter).", "",
             "const wordListLines = <String, String>{"]
    for lang in letters.LANGS:
        index = letters._index(lang)
        body = "\n".join(f"{k} {' '.join(sorted(v))}" for k, v in sorted(index.items()))
        assert '"""' not in body
        lines.append(f"  '{lang}': r\"\"\"\n{body}\"\"\",")
    lines += ["};", "", "/// Letters with a tone mark → without it, dots and hooks kept (letters.untoned).",
              "const untonedLetters = <String, String>{"]
    items = [f"{q(k)}: {q(v)}" for k, v in sorted(untoned_map().items())]
    for i in range(0, len(items), 8):
        lines.append("  " + ", ".join(items[i:i + 8]) + ",")
    lines += ["};", ""]
    return "\n".join(lines)


def dart() -> str:
    words = letters._function_words()
    q = lambda s: "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"  # noqa: E731
    lines = ["// GENERATED by scripts/gen_offline_language.py from content/language_words/: do not edit.",
             "// The function words that tell a Hausa, Yorùbá or Igbo page (backend letters.py), in plain form.",
             "", "const functionWords = <String, Set<String>>{"]
    for lang in ("en", *letters.LANGS):
        lines.append(f"  '{lang}': {{{', '.join(q(w) for w in sorted(words[lang]))}}},")
    lines += ["};", "", "/// Accented, dotted and hooked letters → plain (letters.plain).", "const plainLetters = <String, String>{"]
    pm = plain_map()
    items = [f"{q(k)}: {q(v)}" for k, v in sorted(pm.items())]
    for i in range(0, len(items), 8):
        lines.append("  " + ", ".join(items[i:i + 8]) + ",")
    lines += ["};", f"const minWords = {letters.MIN_WORDS};", f"const margin = {letters.MARGIN};", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    OUT.write_text(dart(), encoding="utf-8")
    WORD_LISTS.write_text(word_lists_dart(), encoding="utf-8")
    print("wrote", OUT.relative_to(ROOT), "and", WORD_LISTS.relative_to(ROOT))
